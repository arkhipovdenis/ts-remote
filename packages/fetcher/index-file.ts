import fs from 'node:fs';
import path from 'node:path';
import { CacheError } from '../shared/errors';
import { FetchResult } from './contract-public';

/**
 * Name of the generated index file inside the cache directory.
 *
 * The index is a plain script `.d.ts` holding one `/// <reference path>` per
 * cached remote. Listing it in the consumer's `tsconfig.json` `files` pulls
 * every remote `declare module "..."` into the program with no Language
 * Service Plugin involved — the only resolution mode available on
 * TypeScript 7, whose native compiler does not load tsserver plugins.
 */
export const INDEX_FILE_NAME = 'ts-remote.index.d.ts';

/**
 * Path of the index file for a given cache directory.
 */
export function getIndexPath(cacheDir: string): string {
  return path.join(path.resolve(cacheDir), INDEX_FILE_NAME);
}

/**
 * Write (or rewrite) the index file referencing every fetched remote.
 * Entries are sorted by module name so the file is stable across runs.
 * Returns the index path.
 */
export function writeIndexFile(cacheDir: string, results: readonly FetchResult[]): string {
  const indexPath = getIndexPath(cacheDir);
  const indexDir = path.dirname(indexPath);

  const references = [...results]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((result) => {
      const relative = path.relative(indexDir, result.cachedPath).split(path.sep).join('/');
      const ref = relative.startsWith('.') ? relative : `./${relative}`;
      return `/// <reference path="${ref}" /> // ${result.name}`;
    });

  const content =
    [
      '// Generated by ts-remote — do not edit.',
      '// Add this file to "files" in tsconfig.json to resolve remote modules without the plugin.',
      ...references,
    ].join('\n') + '\n';

  const tmpPath = indexPath + '.tmp';

  try {
    fs.mkdirSync(indexDir, { recursive: true });
    fs.writeFileSync(tmpPath, content, 'utf-8');
    fs.renameSync(tmpPath, indexPath);
  } catch (err) {
    try {
      fs.unlinkSync(tmpPath);
    } catch {
      // ignore cleanup errors
    }
    throw new CacheError(`Failed to write index file: ${indexPath}`, { cause: err });
  }

  return indexPath;
}
